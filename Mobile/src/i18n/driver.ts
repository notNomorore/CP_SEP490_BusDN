export type DriverTranslation = (typeof driverTranslations)[keyof typeof driverTranslations];

export function useDriverI18n() {
  const language = useLanguageStore((state) => state.language);
  const setLanguage = useLanguageStore((state) => state.setLanguage);
  const toggleLanguage = useLanguageStore((state) => state.toggleLanguage);

  return {
    language,
    setLanguage,
    toggleLanguage,
    t: driverTranslations[language],
  };
}

export function formatDriverStatus(status: string | null | undefined, t: DriverTranslation) {
  const normalized = String(status || 'NOT_STARTED').toUpperCase();
  if (normalized === 'READY') return t.common.ready;
  if (normalized === 'NOT_STARTED') return t.common.notStart;
  if (normalized === 'IN_PROGRESS') return t.common.inProgress;
  if (normalized === 'ISSUE_REPORTED') return t.common.issueReported;
  return normalized.replace(/_/g, ' ').toLowerCase().replace(/\b\w/g, (char) => char.toUpperCase());
}
